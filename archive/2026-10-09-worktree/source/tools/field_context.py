def iau_constellation(ra, dec):
    """Официальное сокращение IAU по границам созвездий (offline-таблица astropy)."""
    return SkyCoord(ra=float(ra) * u.deg, dec=float(dec) * u.deg,
                    frame="icrs").get_constellation(short_name=True)


def scale_note(abbr, pixel_scale_as):
    """Фактическое угловое поле кадра 128×128 px и объяснение масштаба."""
    side_as = 128.0 * float(pixel_scale_as)
    side = f"{side_as / 60.0:.1f}".replace(".", ",")
    ratio = round(1800.0 / side_as)  # видимый поперечник Луны ~30′
    return (f"Кадр — квадрат 128×128 пикселя со стороной около {side}′, "
            f"примерно в {ratio} раз меньше видимого поперечника Луны. "
            + CONSTELLATION_SCALE[abbr])


def sky_context(key, ra, dec, pixel_scale_as):
    """Собрать data.skyContext для контактного поля по ключу manifest."""
    curated = FIELDS.get(key)
    if curated is None:
        raise ValueError(f"Для контактного поля нет небесного контекста: {key}")
    abbr = iau_constellation(ra, dec)
    if abbr not in CONSTELLATIONS_RU:
        raise ValueError(f"Нет русского названия созвездия {abbr} для поля {key}")
    return {
        "constellation": {"name": CONSTELLATIONS_RU[abbr], "abbr": abbr},
        "intro": curated["intro"],
        "lookFor": curated["lookFor"],
        "scaleNote": scale_note(abbr, pixel_scale_as),
        "sources": [list(source) for source in curated["sources"]],
    }


def validate(ctx, where):
    """Минимальная проверка контракта skyContext на границе сборки."""
    required = ("constellation", "intro", "lookFor", "scaleNote", "sources")
    for field in required:
        if not ctx.get(field):
            raise ValueError(f"skyContext.{field} пуст: {where}")
    name, abbr = ctx["constellation"].get("name"), ctx["constellation"].get("abbr")
    if not name or not abbr or CONSTELLATIONS_RU.get(abbr) != name:
        raise ValueError(f"skyContext.constellation не согласован: {where}")
    for label, url in ctx["sources"]:
        if not label or not str(url).startswith("http"):
            raise ValueError(f"skyContext.sources повреждены: {where}")
